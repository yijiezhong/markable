import Foundation
import PDFKit

/// PDF 文本层归一化工具：兼容 WebKit 写出的「部首 / 兼容字符」文本层，并在文档中定位标题。
///
/// 背景：`WKWebView` 生成的 PDF 会把部分汉字映射成**字形相同**的部首或 CJK 兼容字符，
/// 例如「页」→「⻚」（U+2EDA，CJK 部首补充）、「一」→「⼀」（U+2F00，康熙部首）。
/// 这些码位在 Unicode 中与统一汉字并不相同，按字面做 `String.contains` 或
/// `PDFDocument.findString` 会漏掉中文标题，导致目录页码查不到、书签退回首页。
///
/// 本类型做两件事：
/// 1. `normalize`：把上述码位**逐码位 1:1** 映射回统一汉字（不做 NFC/NFKC 组合分解，
///    因此归一化前后的字符数、UTF-16 长度都不变）；
/// 2. `findSelection`：逐页取 `PDFPage.string`，归一化后按「忽略空白 + ASCII 不区分大小写」
///    查找标题，再把命中位置换算回**原文**的 `NSRange`，交给 `PDFPage.selection(for:)`。
///
/// 所有映射数据都内置在源码里（未联网、无外部依赖）。
enum PDFTextNormalizer {
    // MARK: - 归一化

    /// 把部首 / CJK 兼容字符归一化为统一汉字；其余字符（ASCII、普通汉字、emoji 等）原样保留。
    ///
    /// 只做逐码位 1:1 替换，所以 `normalize(s).count == s.count` 且 UTF-16 长度相同，
    /// 归一化文本里找到的位置可以直接映射回原文本（见 `matchRange`）。
    static func normalize(_ text: String) -> String {
        // 常规页面不含部首区码位，先扫一遍确认，避免无谓地重建字符串。
        guard text.unicodeScalars.contains(where: { mapped($0) != nil }) else { return text }

        var result = String()
        result.reserveCapacity(text.unicodeScalars.count)
        for scalar in text.unicodeScalars {
            result.unicodeScalars.append(mapped(scalar) ?? scalar)
        }
        return result
    }

    /// 标题匹配键：归一化（部首/兼容汉字）→ 去所有空白 → ASCII 小写。
    /// 用于「标题锚点 → 页索引」映射与目录/书签的键对齐。
    static func headingKey(_ text: String) -> String {
        normalize(text)
            .filter { !$0.isWhitespace }
            .lowercased()
    }

    // MARK: - 查找

    /// 在整份文档中查找标题，返回第一个命中处的选择（找不到返回 `nil`）。
    ///
    /// 供目录页码与书签目标共用：`selection.pages.first` 即标题所在页，
    /// `selection.bounds(for:)` 可作书签落点。页面文本按 `normalize` 归一化后比较，
    /// 因此「页」能命中文本层里的「⻚」。
    static func findSelection(of title: String, in document: PDFDocument) -> PDFSelection? {
        for index in 0..<document.pageCount {
            guard let page = document.page(at: index),
                  let text = page.string,
                  let range = matchRange(of: title, in: text),
                  let selection = page.selection(for: range) else { continue }
            return selection
        }
        return nil
    }

    /// 在单页文本里查找标题，返回**原文本**中的 UTF-16 范围；找不到返回 `nil`。
    ///
    /// 比较规则：
    /// - 两侧都先按 `normalize` 做部首 / 兼容字符归一化；
    /// - 忽略**所有空白**（换行、多个空格、制表符）——标题在页面里换行时，
    ///   文本层会插入换行符，逐字比较会失败；
    /// - ASCII 字母不区分大小写（中文标题不受影响）。
    static func matchRange(of title: String, in pageText: String) -> NSRange? {
        let needle = searchKey(title)
        guard !needle.isEmpty else { return nil }
        let haystack = searchKey(pageText)
        guard haystack.scalars.count >= needle.scalars.count else { return nil }

        let length = needle.scalars.count
        let lastStart = haystack.scalars.count - length
        var start = 0
        while start <= lastStart {
            // 先比首码位，绝大多数位置一次比较就能跳过。
            if haystack.scalars[start] == needle.scalars[0] {
                var matched = 1
                while matched < length,
                      haystack.scalars[start + matched] == needle.scalars[matched] {
                    matched += 1
                }
                if matched == length {
                    let lower = haystack.startOffsets[start]
                    let upper = haystack.endOffsets[start + length - 1]
                    if upper > lower {
                        return NSRange(location: lower, length: upper - lower)
                    }
                }
            }
            start += 1
        }
        return nil
    }

    // MARK: - 内部实现

    /// 查找键：归一化、去空白、ASCII 小写后的码位序列，外加每个码位在原文中的 UTF-16 范围。
    private struct SearchKey {
        /// 参与比较的码位。
        var scalars: [Unicode.Scalar] = []
        /// 每个码位对应原文 UTF-16 起点。
        var startOffsets: [Int] = []
        /// 每个码位对应原文 UTF-16 终点（不含）。
        var endOffsets: [Int] = []

        var isEmpty: Bool { scalars.isEmpty }
    }

    /// 单码位归一化：只有部首补充 / 康熙部首 / CJK 兼容表意文字区才需要查表。
    private static func mapped(_ scalar: Unicode.Scalar) -> Unicode.Scalar? {
        let value = scalar.value
        guard (value >= 0x2E80 && value <= 0x2FDF) || (value >= 0xF900 && value <= 0xFAFF) else {
            return nil
        }
        guard let target = table[value] else { return nil }
        return Unicode.Scalar(target)
    }

    /// 构造查找键。偏移量按**原文**码位宽度累计，保证命中范围能还原回原文。
    private static func searchKey(_ text: String) -> SearchKey {
        var key = SearchKey()
        let count = text.unicodeScalars.count
        key.scalars.reserveCapacity(count)
        key.startOffsets.reserveCapacity(count)
        key.endOffsets.reserveCapacity(count)

        var utf16Offset = 0
        for original in text.unicodeScalars {
            let scalar = mapped(original) ?? original
            let width = original.value > 0xFFFF ? 2 : 1
            defer { utf16Offset += width }

            if scalar.properties.isWhitespace { continue }

            let folded: Unicode.Scalar
            if scalar.value >= 0x41 && scalar.value <= 0x5A {
                folded = Unicode.Scalar(scalar.value + 0x20) ?? scalar
            } else {
                folded = scalar
            }
            key.scalars.append(folded)
            key.startOffsets.append(utf16Offset)
            key.endOffsets.append(utf16Offset + width)
        }
        return key
    }

